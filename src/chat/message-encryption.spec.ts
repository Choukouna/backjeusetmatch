import { ConfigService } from '@nestjs/config';
import { MessageEncryption } from './message-encryption.js';
describe('Dart-compatible message encryption', () => {
  const encryption = new MessageEncryption(
    new ConfigService({
      CHAT_ENCRYPTION_KEY: '12345678901234567890123456789012',
    }),
  );
  it.each([
    '',
    'Salut 🎾',
    '1234567890123456',
    'Message plus long que seize octets avec accents éè',
  ])('round trips %s', (text) => {
    expect(encryption.decrypt(encryption.encrypt(text))).toBe(text);
  });
  it('decrypts a fixture generated by the existing Dart encrypt library', () => {
    expect(
      encryption.decrypt(
        'AAECAwQFBgcICQoLDA0ODw==:vYCg4pDSCvtOq1sH7ryX30rZ8J7ZDA/MtQ9NPOopiUs=',
      ),
    ).toBe('Salut 🎾, à demain !');
  });
  it('preserves legacy plaintext and rejects corrupt ciphertext', () => {
    expect(encryption.decrypt('ancien message')).toBe('ancien message');
    expect(encryption.decrypt('bad:bad')).toBe('Erreur lors du déchiffrement');
  });
});
